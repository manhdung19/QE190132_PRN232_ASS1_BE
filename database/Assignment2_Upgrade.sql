-- Assignment 2 schema upgrade. Run exactly once against an Assignment 1 database.
-- No Assignment 1 row is deleted or rewritten.
-- Stop on the first error in psql: psql -v ON_ERROR_STOP=1 -f database/Assignment2_Upgrade.sql

BEGIN;
SET LOCAL search_path TO public;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '60s';

DO $$
BEGIN
    IF to_regclass('public."Task"') IS NULL
       OR to_regclass('public."Department"') IS NULL
       OR to_regclass('public."Project"') IS NULL
       OR to_regclass('public."Tag"') IS NULL
       OR to_regclass('public."TaskTag"') IS NULL THEN
        RAISE EXCEPTION 'Assignment 1 schema is missing; upgrade cancelled';
    END IF;

    IF to_regclass('public."SystemAccount"') IS NOT NULL
       OR EXISTS (
           SELECT 1
           FROM pg_attribute
           WHERE attrelid = 'public."Task"'::regclass
             AND attname = 'CreatedByID'
             AND NOT attisdropped
       ) THEN
        RAISE EXCEPTION 'Assignment 2 schema already exists or is partially installed; inspect before retrying';
    END IF;
END $$;

CREATE TABLE public."SystemAccount" (
    "AccountID"   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FullName"    VARCHAR(150) NOT NULL,
    "Email"       VARCHAR(320) NOT NULL,
    "PasswordHash" TEXT NOT NULL,
    "Role"        SMALLINT NOT NULL DEFAULT 0,
    "CreatedDate" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "UQ_SystemAccount_Email" UNIQUE ("Email"),
    CONSTRAINT "CK_SystemAccount_Role" CHECK ("Role" IN (0, 1)),
    CONSTRAINT "CK_SystemAccount_FullName" CHECK (length(btrim("FullName")) > 0),
    CONSTRAINT "CK_SystemAccount_EmailNormalized"
        CHECK (length(btrim("Email")) > 0 AND "Email" = lower(btrim("Email"))),
    CONSTRAINT "CK_SystemAccount_PasswordHash" CHECK (length("PasswordHash") > 0)
);

-- Nullable: legacy Assignment 1 tasks have no known creator.
ALTER TABLE public."Task"
    ADD COLUMN "CreatedByID" INTEGER NULL,
    ADD CONSTRAINT "FK_Task_SystemAccount_CreatedBy"
        FOREIGN KEY ("CreatedByID") REFERENCES public."SystemAccount" ("AccountID")
        ON DELETE RESTRICT;

CREATE INDEX "IX_Task_CreatedByID"
    ON public."Task" ("CreatedByID")
    WHERE "CreatedByID" IS NOT NULL;

COMMIT;
